; Zephyr-80 MAME bank/serial IRQ proof ROM
;
; Source format: SDCC/ASxxxx Z80 assembly, assembled with sdasz80.
; This targets the experimental zephyr_banktst MAME machine.  It validates the
; Phase 6 behavioral serial RX IRQ path; it is not a real UART/SIO driver.

	.module banktest_irq
	.optsdcc -mz80

	.area _CODE

	.globl reset

SER_STATUS	= 0x20
SER_DATA	= 0x21
SER_CTRL	= 0x22

ST_TX_READY	= 0x01
ST_RX_READY	= 0x02

CTRL_RX_IRQ	= 0x01
CTRL_ACK	= 0x80

BANK_MID	= 0x11
BANK_HIGH	= 0x12
MID_RAM		= 0x80

RX_INDEX	= 0xc000
RX_DONE		= 0xc001
RX_ERROR	= 0xc002

reset:
	di
	jp	start

	.db	0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff
	.db	0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff
	.db	0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff
	.db	0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff
	.db	0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff
	.db	0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff
	.db	0xff, 0xff, 0xff, 0xff

irq_entry:
	jp	serial_irq_handler

	.db	0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff
	.db	0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff
	.db	0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff
